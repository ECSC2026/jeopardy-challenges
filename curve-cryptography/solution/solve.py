def recover_translation_by_G(G):
    points = [G]
    for _ in range(4):
        points.append(point_add(points[-1], G))
    P1_points = [map_to_P1(point) for point in points]

    pair_count = len(P1_points) - 1
    rows = []
    for sample_index, (source, target) in enumerate(
        zip(P1_points, P1_points[1:])
    ):
        for output_coordinate in range(2):
            row = [F(0)] * (4 + pair_count)
            offset = 2 * output_coordinate
            row[offset : offset + 2] = source
            row[4 + sample_index] = -target[output_coordinate]
            rows.append(row)

    solution = Matrix(F, rows).right_kernel().basis()[0]
    return Matrix(F, 2, 2, solution[:4])



