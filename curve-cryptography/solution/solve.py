def normalize(point):
    """Choose the representative whose first nonzero coordinate is one."""
    point = vector(F, point)
    pivot = next(coordinate for coordinate in point if coordinate != 0)
    return vector(F, [coordinate / pivot for coordinate in point])


def point_add(P, Q):
    return normalize(add(list(P), list(Q)))


def sample_multiples(number):
    """Obtain G, [2]G, ..., [number]G using only the public law."""
    points = [G]
    while len(points) < number:
        points.append(point_add(points[-1], G))
    return points


def recover_curve_equations(points):
    """Interpolate all quintics vanishing on the sampled projective points."""
    monomials = [(i, j) for i in range(5) for j in range(i, 5)]
    evaluation_matrix = Matrix(
        F,
        [[P[i] * P[j] for i, j in monomials] for P in points],
    )
    print(evaluation_matrix)
    kernel = evaluation_matrix.right_kernel()

    coordinate_ring = PolynomialRing(F, names=("x0", "x1", "x2", "x3", "x4"))
    x = coordinate_ring.gens()
    equations = [
        sum(coeff * x[i] * x[j] for coeff, (i, j) in zip(relation, monomials))
        for relation in kernel.basis()
    ]
    return equations


def recover_parametrization(points):
    """Recover M such that phi(t) = M * [1,t,t^2,t^3].

    We know the parameter values of our samples: the point at index n is [n]G.
    Each projective equality M*[1,n,n^2,n^3,n^4] = lambda_n*[n]G is linear in
    the 25 entries of M and in the unknown projective scales lambda_n.
    """
    sample_count = len(points)
    rows = []
    for sample_index, point in enumerate(points):
        n = F(sample_index + 1)
        powers = [n**i for i in range(4)]
        for output_coordinate in range(4):
            row = [F(0)] * (16 + sample_count)
            offset = 4 * output_coordinate
            row[offset : offset + 4] = powers
            row[16 + sample_index] = -point[output_coordinate]
            rows.append(row)

    solutions = Matrix(F, rows).right_kernel()
    assert solutions.dimension() == 1
    solution = solutions.basis()[0]
    parametrization = Matrix(F, 4, 4, solution[:16])
    assert parametrization.is_invertible()

    for n, expected in enumerate(points, start=1):
        parameter_point = vector(F, [1, n, n**2, n**3])
        assert normalize(parametrization * parameter_point) == expected

    return parametrization


def decode_parameter(parametrization_inverse, point):
    """Apply the birational map C -> P^1 and return its affine parameter."""
    standard_point = parametrization_inverse * vector(F, point)
    assert standard_point[0] != 0
    return standard_point[1] / standard_point[0]


def encode_parameter(parametrization, parameter):
    parameter = F(parameter)
    standard_point = vector(F, [1, parameter, parameter**2, parameter**3])
    return normalize(parametrization * standard_point)


