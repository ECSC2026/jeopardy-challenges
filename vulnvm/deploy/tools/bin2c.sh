#!/bin/sh
# bin2c.sh NAME < input.bin > output.c
# Emit a C source defining `const unsigned char NAME[]` and `NAME_len`.
set -e
name="$1"
[ -n "$name" ] || { echo "usage: bin2c.sh NAME < in > out.c" >&2; exit 2; }

printf '/* generated by tools/bin2c.sh — do not edit */\n'
printf 'const unsigned char %s[] = {\n' "$name"
od -An -v -tu1 | awk '{ for (i = 1; i <= NF; i++) { printf "%s,", $i; if (++n % 16 == 0) printf "\n" } } END { if (n % 16) printf "\n" }'
printf '};\n'
printf 'const unsigned int %s_len = sizeof(%s);\n' "$name" "$name"
