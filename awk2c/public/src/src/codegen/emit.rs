//! C23 emission from the AST, consuming the inferred state computed by
//! [`super::analysis`].
//!
//! Emission is driven by the **shape** of a node, never by a claim about the
//! value it will produce — what a scalar holds is a run-time property. So
//! **every expression has exactly one form**, its `AwkValue` form from
//! [`Codegen::expr`]; [`Codegen::truthy`] and [`Codegen::num`] wrap that in
//! `awk_to_bool`/`awk_to_num` rather than lowering the node a second, cheaper
//! way. That costs some box/unbox round trips in the generated C and buys an
//! emitter with no second lowering to keep in agreement.
//!
//! The operators are the runtime's (`awk_add`, `awk_concat`,
//! `awk_regex_match`), `&&`/`||` excepted, which lower to C's own
//! short-circuiting operators. Comparison in particular is the runtime's job:
//! it goes through the three-way `awk_cmp`, which is what keeps `$1 < $2`
//! numeric and `"10" < "9"` a string comparison. Choosing string-vs-number at
//! compile time cannot be done soundly, so that is a correctness constraint
//! rather than a missing optimization.
//!
//! Correctness is owed only for programs the awk oracle itself accepts.
//! Semantically invalid source may produce C that does not compile, and no
//! clean diagnostic is owed for it — but it may not emit code that quietly
//! leaks or misbehaves, which is why the few unrepresentable cases panic here.

use std::fmt::Write as _;

use crate::ast::{Program, Pattern, Function, Stmt, Expr, UnOp, BinOp};

use super::*;

impl Codegen {
    /// Postfix `lv++`/`lv--`: read `lv`'s current value as a raw `double` `_d`,
    /// store `_d ± 1` back into it, and yield the pre-image.
    ///
    /// A `Field`/`ArrayRef` index is evaluated **once** into temps and then
    /// reused, so a side-effecting subscript such as `a[i++]++` runs `i++` a
    /// single time, matching awk (as in [`Self::rmw`]).
    fn post_incr(&self, lv: &Expr, dec: bool, ctx: &Ctx) -> String {
        let new = format!("awk_num(_d {} 1)", if dec { "-" } else { "+" });
        match lv {
            Expr::Var(name) => format!(
                "({{ double _d = awk_to_num(awk_dup(&{slot})); {}; awk_num(_d); }})",
                Self::scalar_store_void(name, ctx, &new),
                slot = Self::scalar_slot(name, ctx)
            ),
            Expr::Field(idx) => format!(
                "({{ AwkValue _ix = {}; \
                 double _d = awk_to_num(awk_field_get(awk_dup(&_ix))); \
                 awk_field_set(_ix, {new}); awk_num(_d); }})",
                self.expr(idx, ctx)
            ),
            Expr::ArrayRef(name, subs) => format!(
                "({{ {}double _d = awk_to_num(awk_array_get({slot}, _rd, {n})); \
                 awk_array_set({slot}, _sx, {n}, {new}); awk_num(_d); }})",
                self.sub_temps(subs, ctx),
                slot = Self::array_slot(name, ctx),
                n = subs.len()
            ),
            _ => panic!("invalid lvalue"),
        }
    }

    // ---- Emission ---------------------------------------------------------

    pub(super) fn emit(&self, program: &Program) -> String {
        let mut c = String::new();
        c.push_str("/* Generated by awk2c. */\n");
        c.push_str("#include \"awk_runtime.h\"\n#include <stdio.h>\n#include <stdlib.h>\n#include <math.h>\n\n");

        for name in &self.global_scalars {
            writeln!(c, "static AwkValue g_{name} = {{ AWK_UNINIT, 0.0, 0 }};").unwrap();
        }
        for name in &self.global_arrays {
            writeln!(c, "static AwkArray g_{name};").unwrap();
        }
        c.push('\n');

        // Function prototypes then bodies (call-before-definition allowed).
        for f in &program.functions {
            c.push_str(&self.fn_signature(f));
            c.push_str(";\n");
        }
        c.push('\n');
        for f in &program.functions {
            c.push_str(&self.gen_function(f));
        }

        c.push_str(&self.gen_main(program));
        c
    }

    fn fn_signature(&self, f: &Function) -> String {
        let params: Vec<String> = self.funcs[&f.name]
            .iter()
            .map(|(p, arr)| {
                if *arr { format!("AwkArray *p_{p}") } else { format!("AwkValue l_{p}") }
            })
            .collect();
        let params = params.join(", ");
        let plist = if params.is_empty() { "void" } else { params.as_str() };
        format!("AwkValue f_{}({plist})", f.name)
    }

    fn gen_function(&self, f: &Function) -> String {
        let ctx = Ctx { params: &self.funcs[&f.name], site: Site::Func };
        let mut body = String::new();
        for s in &f.body {
            self.gen_stmt(&mut body, s, &ctx, 1);
        }
        // Implicit `return "";`
        format!(
            "{} {{\n{body}    {}return awk_uninit();\n}}\n\n",
            self.fn_signature(f),
            Self::param_frees(&ctx)
        )
    }

    /// Release the scalar parameters, which own the value they were passed.
    fn param_frees(ctx: &Ctx) -> String {
        let mut out = String::new();
        for p in ctx.owned() {
            write!(out, "awk_free(l_{p}); ").unwrap();
        }
        out
    }

    fn gen_main(&self, program: &Program) -> String {
        let mut begin = String::new();
        let mut mainrules = String::new();
        let mut end = String::new();
        let top = Ctx::top(Site::Rule);
        let top_end = Ctx::top(Site::End);

        let mut has_main = false;
        let mut has_end = false;
        let mut range_id = 0;
        let mut range_decls = String::new();

        for item in &program.items {
            match &item.pattern {
                Pattern::Begin => {
                    for s in &item.action {
                        self.gen_stmt(&mut begin, s, &top, 1);
                    }
                }
                Pattern::End => {
                    has_end = true;
                    for s in &item.action {
                        self.gen_stmt(&mut end, s, &top_end, 1);
                    }
                }
                // A main rule: open its guard, emit the action once, close.
                pattern => {
                    has_main = true;
                    let mut close = "        }\n".to_string();
                    match pattern {
                        Pattern::Always => mainrules.push_str("        {\n"),
                        Pattern::Expr(e) => {
                            writeln!(mainrules, "        if ({}) {{", self.truthy(e, &top)).unwrap();
                        }
                        // A range is on from the record its first pattern
                        // matches through the one its second does, so the flag
                        // carries it across records — and short-circuiting keeps
                        // the start pattern from running while it is already on.
                        Pattern::Range(a, b) => {
                            let flag = format!("_range{range_id}");
                            range_id += 1;
                            writeln!(range_decls, "        bool {flag} = false;").unwrap();
                            writeln!(
                                mainrules,
                                "        if ({flag} || {}) {{\n            {flag} = true;",
                                self.truthy(a, &top)
                            ).unwrap();
                            close = format!(
                                "            if ({}) {flag} = false;\n        }}\n",
                                self.truthy(b, &top)
                            );
                        }
                        Pattern::Begin | Pattern::End => unreachable!(),
                    }
                    for s in &item.action {
                        self.gen_stmt(&mut mainrules, s, &top, 3);
                    }
                    mainrules.push_str(&close);
                }
            }
        }

        // END lives in its own function: `exit` inside a user-defined function
        // cannot jump into `main`, so the runtime calls END through a pointer.
        let mut c = String::new();
        if has_end {
            write!(c, "static void awk_end_rules(void) {{\n{end}}}\n\n").unwrap();
        }
        c.push_str("int main(void) {\n    awk_runtime_start();\n");
        if has_end {
            c.push_str("    awk_register_end(awk_end_rules);\n");
        }
        c.push_str(&begin);

        if has_main || has_end {
            c.push_str("    {\n");
            c.push_str(&range_decls);
            c.push_str("        while (awk_next_record()) {\n");
            c.push_str(&mainrules);
            c.push_str("            awk_rec_next: (void)0;\n");
            c.push_str("        }\n");
            c.push_str("    }\n");
        }
        c.push_str("    awk_end: (void)0;\n");
        if has_end {
            c.push_str("    awk_run_end();\n");
        }
        c.push_str("    return awk_runtime_end();\n}\n");
        c
    }

    // ---- Statements -------------------------------------------------------

    fn gen_stmt(&self, out: &mut String, s: &Stmt, ctx: &Ctx, ind: usize) {
        let pad = "    ".repeat(ind);
        match s {
            Stmt::Expr(e) => {
                writeln!(out, "{pad}awk_free({});", self.expr(e, ctx)).unwrap();
            }
            Stmt::Print(args) => {
                let inits = if args.is_empty() {
                    "awk_field_get(awk_num(0))".to_string()
                } else {
                    self.expr_list(args, ctx)
                };
                let n = if args.is_empty() { 1 } else { args.len() };
                writeln!(out, "{pad}{{ AwkValue _a[] = {{ {inits} }}; awk_print(_a, {n}); }}").unwrap();
            }
            Stmt::Printf(args) => {
                let inits = self.expr_list(args, ctx);
                writeln!(out, "{pad}{{ AwkValue _a[] = {{ {inits} }}; awk_printf(_a, {}); }}", args.len()).unwrap();
            }
            Stmt::If(cond, then, els) => {
                writeln!(out, "{pad}if ({}) {{", self.truthy(cond, ctx)).unwrap();
                self.gen_stmt(out, then, ctx, ind + 1);
                write!(out, "{pad}}}").unwrap();
                if let Some(e) = els {
                    out.push_str(" else {\n");
                    self.gen_stmt(out, e, ctx, ind + 1);
                    writeln!(out, "{pad}}}").unwrap();
                } else {
                    out.push('\n');
                }
            }
            Stmt::While(cond, body) => {
                writeln!(out, "{pad}while ({}) {{", self.truthy(cond, ctx)).unwrap();
                self.gen_stmt(out, body, ctx, ind + 1);
                writeln!(out, "{pad}}}").unwrap();
            }
            Stmt::DoWhile(body, cond) => {
                writeln!(out, "{pad}do {{").unwrap();
                self.gen_stmt(out, body, ctx, ind + 1);
                writeln!(out, "{pad}}} while ({});", self.truthy(cond, ctx)).unwrap();
            }
            Stmt::For(init, cond, update, body) => {
                let init_c = init.as_ref().map(|s| self.stmt_as_void(s, ctx)).unwrap_or_default();
                let cond_c = cond.as_ref().map(|e| self.truthy(e, ctx)).unwrap_or_default();
                let upd_c = update.as_ref().map(|s| self.stmt_as_void(s, ctx)).unwrap_or_default();
                writeln!(out, "{pad}for ({init_c}; {cond_c}; {upd_c}) {{").unwrap();
                self.gen_stmt(out, body, ctx, ind + 1);
                writeln!(out, "{pad}}}").unwrap();
            }
            Stmt::ForIn(var, array, body) => self.gen_for_in(out, var, array, body, ctx, ind),
            Stmt::Block(stmts) => {
                writeln!(out, "{pad}{{").unwrap();
                for st in stmts {
                    self.gen_stmt(out, st, ctx, ind + 1);
                }
                writeln!(out, "{pad}}}").unwrap();
            }
            Stmt::Next => writeln!(out, "{pad}goto awk_rec_next;").unwrap(),
            Stmt::Exit(e) => {
                // Inside a user function there is no label to reach, so the
                // runtime runs END (if still pending) and terminates. In END
                // itself, leaving the END function is all that is left to do.
                let leave = match ctx.site {
                    Site::Func => "awk_exit_now();",
                    Site::End => "return;",
                    Site::Rule => "goto awk_end;",
                };
                if let Some(e) = e {
                    writeln!(out, "{pad}awk_exit({}); {leave}", self.num(e, ctx)).unwrap();
                } else {
                    writeln!(out, "{pad}{leave}").unwrap();
                }
            }
            // The value is built before the owned parameters are released, since
            // it may be (or hold a string shared with) one of them.
            Stmt::Return(e) => {
                let val = e.as_ref().map_or_else(|| "awk_uninit()".to_string(), |e| self.expr(e, ctx));
                writeln!(out, "{pad}{{ AwkValue _r = {val}; {}return _r; }}", Self::param_frees(ctx)).unwrap();
            }
            Stmt::Break => writeln!(out, "{pad}break;").unwrap(),
            Stmt::Continue => writeln!(out, "{pad}continue;").unwrap(),
            Stmt::Delete(name, subs) => {
                let slot = Self::array_slot(name, ctx);
                if subs.is_empty() {
                    writeln!(out, "{pad}awk_array_clear({slot});").unwrap();
                } else {
                    let (vec, n) = self.subs(subs, ctx);
                    writeln!(out, "{pad}awk_array_del({slot}, {vec}, {n});").unwrap();
                }
            }
        }
    }

    /// `for (var in array)`: grab the entry vector and count once up front, then
    /// pull each key straight out of it — no snapshot copy to allocate or free.
    fn gen_for_in(&self, out: &mut String, var: &str, array: &str, body: &Stmt, ctx: &Ctx, ind: usize) {
        let pad = "    ".repeat(ind);
        let slot = Self::array_slot(array, ctx);
        let store = Self::scalar_store_void(var, ctx, "awk_str_own(awk_str_retain(_es[_i].key))");
        writeln!(out, "{pad}{{ AwkEntry *_es = ({slot})->ents; size_t _n = ({slot})->len;").unwrap();
        writeln!(out, "{pad}  for (size_t _i = 0; _i < _n; _i++) {{").unwrap();
        writeln!(out, "{pad}    {store};").unwrap();
        self.gen_stmt(out, body, ctx, ind + 2);
        writeln!(out, "{pad}  }} }}").unwrap();
    }

    /// Render an expr-statement as a void-typed C expression (for `for` heads).
    fn stmt_as_void(&self, s: &Stmt, ctx: &Ctx) -> String {
        match s {
            Stmt::Expr(e) => format!("awk_free({})", self.expr(e, ctx)),
            _ => "(void)0".to_string(),
        }
    }

    // ---- Expressions ------------------------------------------------------

    /// The `AwkValue` form of an expression — the one form every node has.
    ///
    /// Several runtime entry points answer with a C `int`/`double` rather than a
    /// value (`awk_array_in`, `awk_regex_match`, `awk_next_record`, `split`, the
    /// math built-ins); those are the `awk_num(...)` arms below. Nothing here
    /// looks at what a value will *hold* — that is a run-time property.
    fn expr(&self, e: &Expr, ctx: &Ctx) -> String {
        match e {
            Expr::Num(n) => format!("awk_num({})", fmt_double(*n)),
            Expr::Str(s) => format!("awk_str({})", c_string_literal(s)),
            Expr::Var(name) => Self::scalar_read(name, ctx),
            Expr::Field(idx) => format!("awk_field_get({})", self.expr(idx, ctx)),
            Expr::ArrayRef(name, subs) => {
                let slot = Self::array_slot(name, ctx);
                let (vec, n) = self.subs(subs, ctx);
                format!("awk_array_get({slot}, {vec}, {n})")
            }
            Expr::In(subs, name) => {
                let slot = Self::array_slot(name, ctx);
                let (vec, n) = self.subs(subs, ctx);
                format!("awk_num(awk_array_in({slot}, {vec}, {n}))")
            }
            // A bare regex as a value means ($0 ~ /re/).
            Expr::Regex(re) => format!(
                "awk_num(awk_regex_match(awk_field_get(awk_num(0.0)), awk_str({})))",
                c_string_literal(re.as_bytes())
            ),
            Expr::Match(neg, a, b) => format!(
                "awk_num({}awk_regex_match({}, {}))",
                if *neg { "!" } else { "" },
                self.expr(a, ctx),
                self.regex_pat(b, ctx)
            ),
            Expr::Getline(None) => "awk_num(awk_next_record())".to_string(),
            // getline var: store the line into lv, yield the status.
            Expr::Getline(Some(lv)) => {
                let store = self.lval_store_void(lv, "_line", ctx);
                format!("awk_num(({{ AwkValue _line; bool _s = awk_getline_into(&_line); \
                         if (_s) {store}; _s; }}))")
            }
            Expr::Assign(op, target, rhs) => self.gen_assign(*op, target, rhs, ctx),
            Expr::Ternary(c, t, f) => {
                format!("({} ? ({}) : ({}))", self.truthy(c, ctx), self.expr(t, ctx), self.expr(f, ctx))
            }
            Expr::Binary(op, a, b) => self.binary(*op, a, b, ctx),
            // Every unary operator yields a number whatever its operand holds —
            // `+x` included, which is what makes it a conversion and not a no-op.
            Expr::Unary(UnOp::Neg, a) => format!("awk_num(-awk_to_num({}))", self.expr(a, ctx)),
            Expr::Unary(UnOp::Pos, a) => format!("awk_num(awk_to_num({}))", self.expr(a, ctx)),
            Expr::Unary(UnOp::Not, a) => format!("awk_num(!{})", self.truthy(a, ctx)),
            Expr::Concat(a, b) => {
                format!("awk_concat({}, {})", self.expr(a, ctx), self.expr(b, ctx))
            }
            // Prefix yields the new value, so it is a plain read-modify-write;
            // postfix has to keep the old one (see `post_incr`).
            Expr::Incr { pre: true, dec, target } => {
                let f = if *dec { "awk_sub" } else { "awk_add" };
                self.rmw(target, |r| format!("{f}({r}, awk_num(1))"), ctx)
            }
            Expr::Incr { pre: false, dec, target } => self.post_incr(target, *dec, ctx),
            Expr::Call(name, args) => self.gen_call(name, args, ctx),
            Expr::Builtin(name, args) => self.gen_builtin(name, args, ctx),
        }
    }

    /// The pattern argument of a regex operation. A literal `/re/` is its own
    /// text, where `expr` would read a bare regex as the *value* `($0 ~ /re/)`;
    /// anything else supplies the pattern dynamically.
    fn regex_pat(&self, pat: &Expr, ctx: &Ctx) -> String {
        match pat {
            Expr::Regex(re) => format!("awk_str({})", c_string_literal(re.as_bytes())),
            other => self.expr(other, ctx),
        }
    }

    /// The runtime entry point for an arithmetic operator. Shared by the binary
    /// form and compound assignment, so `a % b` and `a %= b` cannot disagree.
    fn arith_fn(op: BinOp) -> &'static str {
        match op {
            BinOp::Add => "awk_add", BinOp::Sub => "awk_sub", BinOp::Mul => "awk_mul",
            BinOp::Div => "awk_div", BinOp::Mod => "awk_mod", BinOp::Pow => "awk_pow",
            _ => unreachable!("not an arithmetic operator: {op:?}"),
        }
    }

    fn binary(&self, op: BinOp, a: &Expr, b: &Expr, ctx: &Ctx) -> String {
        let cmp = match op {
            BinOp::Lt => "<", BinOp::Le => "<=", BinOp::Gt => ">",
            BinOp::Ge => ">=", BinOp::Eq => "==", BinOp::Ne => "!=",
            // C's `&&`/`||` short-circuit exactly as awk's do.
            BinOp::And => {
                return format!("awk_num({} && {})", self.truthy(a, ctx), self.truthy(b, ctx))
            }
            BinOp::Or => {
                return format!("awk_num({} || {})", self.truthy(a, ctx), self.truthy(b, ctx))
            }
            _ => {
                return format!("{}({}, {})",
                               Self::arith_fn(op), self.expr(a, ctx), self.expr(b, ctx))
            }
        };
        // A comparison never specializes to a C operator: deciding
        // string-vs-number from the operands' kinds *is* the strnum rule, and
        // guessing it here would break `"10" < "9"`. The runtime's three-way
        // `awk_cmp` is the only form.
        format!("awk_num(awk_cmp({}, {}) {cmp} 0)", self.expr(a, ctx), self.expr(b, ctx))
    }

    /// Emit a C `int` truth test for `e`.
    fn truthy(&self, e: &Expr, ctx: &Ctx) -> String {
        format!("awk_to_bool({})", self.expr(e, ctx))
    }

    /// Emit a C `double` for `e`, for the entry points that take a plain one:
    /// `awk_exit` and the math built-ins.
    fn num(&self, e: &Expr, ctx: &Ctx) -> String {
        format!("awk_to_num({})", self.expr(e, ctx))
    }

    fn gen_assign(&self, op: Option<BinOp>, target: &Expr, rhs: &Expr, ctx: &Ctx) -> String {
        let rhs_c = self.expr(rhs, ctx);
        let Some(op) = op else {
            return self.lval_store(target, &rhs_c, ctx);
        };
        // Compound assignment is a read-modify-write: route through `rmw` so a
        // Field/ArrayRef index is evaluated exactly once (see there).
        let f = Self::arith_fn(op);
        self.rmw(target, |read| format!("{f}({read}, {rhs_c})"), ctx)
    }

    /// Read-modify-write on `lv`, yielding the owned new value. `mk_new` maps a
    /// C expression that reads the current (owned) value to the new value to
    /// store. For a `Field`/`ArrayRef` the index/subscripts are evaluated **once**
    /// into temps, then reused (dup'd) for the read and consumed by the store —
    /// so a side-effecting subscript such as `a[i++] += 1` runs `i++` a single
    /// time, matching awk. A `Var` has no index, so it keeps the plain path.
    fn rmw(&self, lv: &Expr, mk_new: impl FnOnce(String) -> String, ctx: &Ctx) -> String {
        match lv {
            Expr::Var(_) => {
                let new = mk_new(self.expr(lv, ctx));
                self.lval_store(lv, &new, ctx)
            }
            Expr::Field(idx) => {
                let ix = self.expr(idx, ctx);
                let new = mk_new("awk_field_get(awk_dup(&_ix))".to_string());
                format!("({{ AwkValue _ix = {ix}; AwkValue _nv = {new}; \
                         awk_field_set(_ix, awk_dup(&_nv)); _nv; }})")
            }
            Expr::ArrayRef(name, subs) => {
                let slot = Self::array_slot(name, ctx);
                let n = subs.len();
                let temps = self.sub_temps(subs, ctx);
                let new = mk_new(format!("awk_array_get({slot}, _rd, {n})"));
                format!("({{ {temps}AwkValue _nv = {new}; \
                         awk_array_set({slot}, _sx, {n}, awk_dup(&_nv)); _nv; }})")
            }
            _ => panic!("invalid lvalue"),
        }
    }

    /// The subscript temporaries an `ArrayRef` read and store share: `_sx` holds
    /// the one evaluation of the subscripts, which the store consumes, and `_rd`
    /// the dups the read borrows.
    fn sub_temps(&self, subs: &[Expr], ctx: &Ctx) -> String {
        let dups: Vec<String> = (0..subs.len()).map(|i| format!("awk_dup(&_sx[{i}])")).collect();
        format!("AwkValue _sx[] = {{ {} }}; AwkValue _rd[] = {{ {} }}; ",
                self.expr_list(subs, ctx), dups.join(", "))
    }

    fn gen_call(&self, name: &str, args: &[Expr], ctx: &Ctx) -> String {
        let params = self.funcs.get(name);
        let arity = params.map_or(args.len(), Vec::len);
        let mut parts = Vec::new();
        let mut scratch = Vec::new();
        for i in 0..arity {
            match (params.is_some_and(|p| p[i].1), args.get(i)) {
                (true, Some(Expr::Var(n))) => parts.push(Self::array_slot(n, ctx)),
                // An array parameter with no caller-supplied array needs
                // somewhere to live: the "extra params as locals" idiom relies
                // on a fresh empty array per call, owned by the call expression
                // and released after it.
                (true, _) => {
                    scratch.push(i);
                    parts.push(format!("&_sc{i}"));
                }
                (false, Some(a)) => parts.push(self.expr(a, ctx)),
                (false, None) => parts.push("awk_uninit()".to_string()),
            }
        }
        let call = format!("f_{name}({})", parts.join(", "));
        if scratch.is_empty() {
            return call;
        }
        let (mut decls, mut frees) = (String::new(), String::new());
        for i in &scratch {
            write!(decls, "AwkArray _sc{i} = {{0}}; ").unwrap();
            write!(frees, "awk_array_free(&_sc{i}); ").unwrap();
        }
        format!("({{ {decls}AwkValue _rc = {call}; {frees}_rc; }})")
    }

    // ---- Lvalues ----------------------------------------------------------

    /// Store `value` (owned) into lvalue; statement-expr yields the stored value.
    /// The slot gets a dup so the original can be handed back — which is why a
    /// discarded store should go through [`Self::lval_store_void`] instead.
    fn lval_store(&self, lv: &Expr, value: &str, ctx: &Ctx) -> String {
        let store = self.lval_store_void(lv, "awk_dup(&_v)", ctx);
        format!("({{ AwkValue _v = {value}; {store}; _v; }})")
    }

    /// Store `value` (owned) into lvalue, discarding it: the caller does not
    /// want the stored value back, so nothing is dup'd or freed afterwards.
    fn lval_store_void(&self, lv: &Expr, value: &str, ctx: &Ctx) -> String {
        match lv {
            Expr::Var(name) => Self::scalar_store_void(name, ctx, value),
            Expr::Field(idx) => format!("awk_field_set({}, {value})", self.expr(idx, ctx)),
            Expr::ArrayRef(name, subs) => {
                let slot = Self::array_slot(name, ctx);
                let (vec, n) = self.subs(subs, ctx);
                format!("awk_array_set({slot}, {vec}, {n}, {value})")
            }
            _ => panic!("invalid lvalue"),
        }
    }

    /// The C slot of a scalar: a parameter, a special variable, or a global.
    fn scalar_slot(name: &str, ctx: &Ctx) -> String {
        if ctx.local(name).is_some() {
            format!("l_{name}")
        } else if is_special_scalar(name) {
            format!("awk_v_{name}")
        } else {
            format!("g_{name}")
        }
    }

    fn scalar_read(name: &str, ctx: &Ctx) -> String {
        format!("awk_dup(&{})", Self::scalar_slot(name, ctx))
    }

    fn scalar_store_void(name: &str, ctx: &Ctx, value: &str) -> String {
        if name == "NF" && ctx.local(name).is_none() {
            // Assigning NF rebuilds $0, so it is not a plain slot write.
            format!("awk_set_nf({value})")
        } else {
            format!("awk_store(&{}, {value})", Self::scalar_slot(name, ctx))
        }
    }

    fn array_slot(name: &str, ctx: &Ctx) -> String {
        // A local that isn't an array param falls through: a scalar param used
        // as an array shouldn't happen for valid programs.
        if ctx.local(name) == Some(true) {
            format!("p_{name}")
        } else {
            format!("&g_{name}")
        }
    }

    /// The `AwkValue` forms of `es`, comma-joined — an argument list, a
    /// subscript list, or the initializers of an `AwkValue[]`.
    fn expr_list(&self, es: &[Expr], ctx: &Ctx) -> String {
        es.iter().map(|e| self.expr(e, ctx)).collect::<Vec<_>>().join(", ")
    }

    /// Build a `(AwkValue[]){...}` compound literal + count for subscripts.
    fn subs(&self, subs: &[Expr], ctx: &Ctx) -> (String, usize) {
        (format!("(AwkValue[]){{ {} }}", self.expr_list(subs, ctx)), subs.len())
    }

    /// The `AwkValue` form of a built-in call — the one form it has, like every
    /// other node. Many answer with a C `int`/`double` rather than a value (the
    /// math functions, `split`, `sub`/`gsub`, the I/O helpers); those are
    /// `awk_num(...)` arms, exactly as `awk_array_in` and `awk_cmp` are in
    /// [`Self::expr`] and [`Self::binary`].
    fn gen_builtin(&self, name: &str, args: &[Expr], ctx: &Ctx) -> String {
        let e = |i: usize| self.expr(&args[i], ctx);
        let n = |i: usize| self.num(&args[i], ctx);
        match name {
            // ---- String functions ----
            "length" => match args.first() {
                None => "awk_str_length(awk_field_get(awk_num(0)))".to_string(),
                Some(Expr::Var(n)) if self.is_array_name(n, ctx) => {
                    format!("awk_array_length({})", Self::array_slot(n, ctx))
                }
                Some(_) => format!("awk_str_length({})", e(0)),
            },
            "substr" => match args.get(2) {
                Some(len) => format!("awk_substr({}, {}, {}, true)", e(0), e(1), self.expr(len, ctx)),
                None => format!("awk_substr({}, {}, awk_uninit(), false)", e(0), e(1)),
            },
            "index" => format!("awk_index({}, {})", e(0), e(1)),
            "toupper" => format!("awk_toupper({})", e(0)),
            "tolower" => format!("awk_tolower({})", e(0)),
            "sprintf" => {
                let inits = self.expr_list(args, ctx);
                format!("({{ AwkValue _a[] = {{ {inits} }}; awk_sprintf(_a, {}); }})", args.len())
            }
            "match" => format!("awk_match({}, {})", e(0), self.regex_pat(&args[1], ctx)),

            // ---- Built-ins whose runtime entry point answers with a number ----
            "split" => {
                // The array is where the whole call's result lives, so there is
                // nothing to emit without a name to put it in. Valid awk always
                // has one; a scratch array here would only be a place for the
                // pieces to leak.
                let Some(Expr::Var(arr)) = args.get(1) else {
                    panic!("split's second argument must be an array name");
                };
                let slot = Self::array_slot(arr, ctx);
                match args.get(2) {
                    // No separator: `awk_split` reads FS itself.
                    None => format!("awk_num(awk_split({}, {slot}, NULL))", e(0)),
                    // `awk_split` borrows the separator as a plain `const char
                    // *`, so the value is consumed for its string and that
                    // reference released after the call. A literal `/re/` goes
                    // through `regex_pat`, which gives its text rather than the
                    // match value a bare regex would otherwise read as.
                    Some(other) => format!(
                        "awk_num(({{ AwkValue _s = {}; char *_fs = awk_to_str({}); \
                         size_t _n = awk_split(_s, {slot}, _fs); \
                         awk_str_release(_fs); (double)_n; }}))",
                        e(0), self.regex_pat(other, ctx)),
                }
            }
            "sub" | "gsub" => {
                let global = if name == "gsub" { "true" } else { "false" };
                // The pattern is evaluated into a temp so that pattern,
                // replacement and target still run in source order.
                let patdecl = format!("AwkValue _pat = {}; ", self.regex_pat(&args[0], ctx));
                let (read, store) = if args.len() >= 3 {
                    (self.expr(&args[2], ctx),
                     self.lval_store_void(&args[2], "_subv", ctx))
                } else {
                    ("awk_field_get(awk_num(0))".to_string(),
                     "awk_field_set(awk_num(0), _subv)".to_string())
                };
                format!("awk_num(({{ {patdecl}AwkValue _repl = {}; \
                         AwkValue _tgt = {read}; size_t _cnt; \
                         AwkValue _subv = awk_subst(_pat, _repl, _tgt, {global}, &_cnt); \
                         {store}; (double)_cnt; }}))", e(1))
            }

            // ---- Math functions ----
            "sin" => format!("awk_num(sin({}))", n(0)),
            "cos" => format!("awk_num(cos({}))", n(0)),
            "atan2" => format!("awk_num(atan2({}, {}))", n(0), n(1)),
            "exp" => format!("awk_num(exp({}))", n(0)),
            "log" => format!("awk_num(log({}))", n(0)),
            "sqrt" => format!("awk_num(sqrt({}))", n(0)),
            "int" => format!("awk_num(trunc({}))", n(0)),
            "rand" => "awk_num(awk_rand())".to_string(),
            "srand" => {
                if args.is_empty() {
                    "awk_num(awk_srand(0, false))".to_string()
                } else {
                    format!("awk_num(awk_srand({}, true))", n(0))
                }
            }

            // ---- I/O helpers ----
            "fflush" => {
                if args.is_empty() {
                    "awk_num(({ fflush(stdout); 0; }))".to_string()
                } else {
                    format!("awk_num(({{ awk_free({}); fflush(stdout); 0; }}))", e(0))
                }
            }
            "close" => {
                if args.is_empty() {
                    "awk_num(0)".to_string()
                } else {
                    format!("awk_num(({{ awk_free({}); 0; }}))", e(0))
                }
            }
            "system" => "awk_num(({ awk_fatal(\"system() is not supported\"); 0; }))".to_string(),

            other => unimplemented!("builtin `{other}`"),
        }
    }

    fn is_array_name(&self, name: &str, ctx: &Ctx) -> bool {
        ctx.local(name).unwrap_or_else(|| self.global_arrays.contains(name))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Where emission has a choice the E2E harness cannot see — it compares
    /// program *output*, not the C that produced it — the shape is asserted here.
    #[test]
    fn a_global_scalar_is_an_awkvalue() {
        let c = compile("BEGIN { s = \"a\" \"b\"; print s }");
        assert!(c.contains("static AwkValue g_s"), "{c}");
    }

    #[test]
    fn every_comparison_goes_through_the_runtime() {
        // No comparison specializes to a C operator, not even between literals:
        // deciding string-vs-number is the runtime's job under the strnum rules.
        let c = compile("BEGIN { x = 1; if (x < 2) print \"y\" }");
        assert!(c.contains("awk_cmp(awk_dup(&g_x), awk_num(2.0)) < 0"), "{c}");
    }

    #[test]
    fn strnum_comparisons_stay_on_the_runtime() {
        // The `"10" < "9"` lever: fields carry no static type, so the runtime
        // has to decide string-vs-number from the operand kinds.
        let c = compile("{ if ($1 < $2) print \"y\" }");
        assert!(c.contains("awk_cmp(awk_field_get(awk_num(1.0)), awk_field_get(awk_num(2.0))) < 0"), "{c}");
    }

    #[test]
    fn logical_operators_short_circuit_in_c() {
        // C's `&&`/`||` short-circuit exactly as awk's do, so the operands stay
        // in the condition rather than being evaluated into arguments.
        let c = compile("BEGIN { n = 1 && 2 }");
        assert!(c.contains("awk_num(awk_to_bool(awk_num(1.0)) && awk_to_bool(awk_num(2.0)))"), "{c}");
    }

    #[test]
    fn unary_plus_is_a_conversion_not_a_no_op() {
        // `+x` is a number whatever `x` holds, so it cannot emit `x` unchanged.
        let c = compile("BEGIN { print +s }");
        assert!(c.contains("awk_num(awk_to_num(awk_dup(&g_s)))"), "{c}");
    }

    #[test]
    fn an_array_parameter_with_no_argument_gets_a_scratch_array() {
        // Otherwise the callee's writes into it would leak.
        let c = compile("function f(a) { a[1] = 1 } BEGIN { f() }");
        assert!(c.contains("AwkArray _sc0 = {0};"), "{c}");
        assert!(c.contains("awk_array_free(&_sc0);"), "{c}");
    }

    #[test]
    fn a_postfix_increment_yields_the_pre_image() {
        let c = compile("{ n = $1; n++ }");
        assert!(c.contains("double _d = awk_to_num(awk_dup(&g_n));"), "{c}");
        assert!(c.contains("awk_store(&g_n, awk_num(_d + 1)); awk_num(_d);"), "{c}");
    }

    #[test]
    fn concatenation_folds_left() {
        let c = compile("BEGIN { print a b c }");
        assert!(c.contains("awk_concat(awk_concat(awk_dup(&g_a), awk_dup(&g_b)), awk_dup(&g_c))"), "{c}");
    }

    #[test]
    fn a_literal_regex_in_pattern_position_is_its_own_text() {
        // Not the *value* a bare regex has, which is the `$0 ~ /re/` match.
        let c = compile("{ if ($1 ~ /x/) print }");
        assert!(c.contains(r#"awk_regex_match(awk_field_get(awk_num(1.0)), awk_str("x"))"#), "{c}");
        // A dynamic pattern reaches the same entry point.
        let c = compile("{ if ($1 ~ $2) print }");
        assert!(c.contains("awk_regex_match(awk_field_get"), "{c}");
    }

    #[test]
    fn a_bare_regex_is_a_match_against_the_record() {
        // `/re/` in value position means `$0 ~ /re/`, which is what makes it
        // work as a rule's pattern.
        let c = compile("/x/ { n++ }");
        assert!(c.contains(r#"awk_regex_match(awk_field_get(awk_num(0.0)), awk_str("x"))"#), "{c}");
        // Written out explicitly it is the same match.
        let c = compile("$0 ~ /x/ { n++ }");
        assert!(c.contains(r#"awk_regex_match(awk_field_get(awk_num(0.0)), awk_str("x"))"#), "{c}");
    }

    #[test]
    #[should_panic(expected = "split's second argument must be an array name")]
    fn split_with_nowhere_to_put_the_pieces_is_a_codegen_error() {
        // The array *is* the result, so there is nothing to emit without one —
        // and no valid program gets here. Invalid source owes no clean
        // diagnostic, but it may not emit code that quietly leaks.
        compile("BEGIN { n = split(\"a b\") }");
    }

    #[test]
    fn a_returned_value_outlives_the_parameters() {
        // The value may be, or share a string with, a parameter about to be
        // released, so it is built into a temp first.
        let c = compile("function g(a) { return a \"!\" } BEGIN { print g(1) }");
        assert!(c.contains("awk_free(l_a); return _r;"), "{c}");
    }
}
